export function neutralizeTeacherVoice(text: string): string {
  if (!text) return text;
  let next = text;
  for (const [from, to] of PHRASES) next = next.split(from).join(to);
  for (const [from, to] of WORDS) next = next.split(from).join(to);
  return next;
}
